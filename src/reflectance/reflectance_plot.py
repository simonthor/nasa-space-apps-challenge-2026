
from pathlib import Path
import argparse

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

# Reuse the functions and ocean definitions
# from your existing working analysis.
from reflectance.reflectance_analysis import OCEANS, monthly_reflectance


parser = argparse.ArgumentParser()

parser.add_argument("--data-dir", type=Path, required=True)

parser.add_argument(
    "--results-dir",
    type=Path,
    default=Path("reflectance_results")
)

args = parser.parse_args()

root = args.data_dir.resolve()
out = args.results_dir.resolve()
out.mkdir(parents=True, exist_ok=True)


# ==================================================
# GRAPH 1: MONTHLY REFLECTANCE OVER TIME
# ==================================================

for ocean, folders in OCEANS.items():

    # Load the same three regions as the original code.
    series = {}

    for name, folder in zip(
        ("Patch", "North", "South"), folders
    ):
        file_path = (
            root / folder / "reflectance_monthly.nc"
        )
        series[name] = monthly_reflectance(file_path)

    # Only retain matching months.
    data = pd.DataFrame(series).dropna()

    # Match the complete-year rule of our analysis.
    counts = data.groupby(data.index.year).size()
    years = counts[counts == 12].index
    data = data[data.index.year.isin(years)].copy()

    # Average of the North and South controls.
    data["Control"] = (
        data["North"] + data["South"]
    ) / 2

    # Monthly patch minus control difference.
    data["Difference"] = (
        data["Patch"] - data["Control"]
    )

    fig, (ax1, ax2) = plt.subplots(
        2, 1,
        figsize=(11, 7),
        sharex=True
    )

    # Smooth monthly fluctuations using a
    # 12-month moving average for readability.
    for region in ("Patch", "North", "South"):

        smoothed = data[region].rolling(
            12, min_periods=12
        ).mean()

        ax1.plot(
            data.index,
            smoothed,
            label=region
        )

    ax1.set_title(f"{ocean} — Reflectance at 531 nm")
    ax1.set_ylabel("Rrs_531 (sr^-1)")
    ax1.legend()
    ax1.grid(alpha=0.3)

    # Plot how the difference changes over time.
    difference = data["Difference"].rolling(
        12, min_periods=12
    ).mean()

    ax2.plot(data.index, difference)

    # Horizontal zero indicates equal reflectance.
    ax2.axhline(
        0,
        color="black",
        linestyle="--"
    )

    ax2.set_title("Patch minus average control")
    ax2.set_ylabel("Difference (sr^-1)")
    ax2.set_xlabel("Year")
    ax2.grid(alpha=0.3)

    fig.tight_layout()

    filename = (
        ocean.lower().replace(" ", "_")
        + "_timeseries.png"
    )

    fig.savefig(out / filename, dpi=180)
    plt.close(fig)


# ==================================================
# GRAPH 2: LONG-TERM MEANS FOR ALL FIVE OCEANS
# ==================================================

# Read the summary generated by compare_patches.py.
summary = pd.read_csv(
    out / "five_oceans_reflectance.csv"
)

means = summary.set_index("ocean")[
    ["patch_mean", "north_mean", "south_mean"]
]

ax = means.plot.bar(
    figsize=(11, 5),
    width=0.75
)

ax.set_title("Average reflectance across five oceans")
ax.set_ylabel("Rrs_531 (sr^-1)")
ax.set_xlabel("")
ax.legend(["Patch", "North", "South"])
ax.tick_params(axis="x", rotation=20)
ax.grid(axis="y", alpha=0.25)

plt.tight_layout()
plt.savefig(out / "all_oceans_means.png", dpi=180)
plt.close()


# ==================================================
# GRAPH 3: MEAN DIFFERENCES WITH 95% CI
# ==================================================

fig, ax = plt.subplots(figsize=(10, 5))

positions = np.arange(len(summary))

# Draw the confidence intervals as horizontal lines.
for i, row in summary.iterrows():

    ax.plot(
        [row["ci95_low"], row["ci95_high"]],
        [i, i],
        linewidth=3,
        marker="|",
        markersize=12
    )

    # Point = estimated mean difference.
    ax.scatter(
        row["difference"],
        i,
        s=65,
        zorder=3
    )

# Vertical reference: zero difference.
ax.axvline(
    0,
    color="black",
    linestyle="--",
    linewidth=1
)

ax.set_yticks(
    positions,
    summary["ocean"]
)

ax.invert_yaxis()

ax.set_xlabel(
    "Patch minus average control (sr^-1)"
)

ax.set_title(
    "Mean reflectance differences with 95% CI"
)

ax.grid(axis="x", alpha=0.3)

fig.tight_layout()
fig.savefig(
    out / "confidence_intervals.png",
    dpi=180
)
plt.close(fig)

print("Graphs saved in:", out)